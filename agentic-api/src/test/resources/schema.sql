CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    nickname VARCHAR(100),
    monthly_income BIGINT DEFAULT 0,
    fixed_expense BIGINT DEFAULT 0,
    fcm_token VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    slot_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    item_name VARCHAR(255) NOT NULL,
    item_image_url VARCHAR(500),
    target_amount BIGINT NOT NULL,
    current_amount BIGINT NOT NULL DEFAULT 0,
    achievement_rate DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    registration_type VARCHAR(50) NOT NULL,
    daily_budget BIGINT,
    duration_days INT,
    estimated_completion_date DATE,
    withdrawal_condition VARCHAR(2000),
    lock_id VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT FK_goals_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    goal_id BIGINT,
    mission_source VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    category VARCHAR(50),
    description VARCHAR(500),
    limit_amount BIGINT,
    deposit_amount BIGINT,
    duration_days INT,
    start_date DATE,
    end_date DATE,
    overage_rate DOUBLE PRECISION,
    proposal_reason VARCHAR(2000),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT FK_missions_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT FK_missions_goal FOREIGN KEY (goal_id) REFERENCES goals(id)
);

CREATE TABLE IF NOT EXISTS deposits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    amount BIGINT NOT NULL,
    imkrw_amount BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    lock_tx_hash VARCHAR(200),
    release_tx_hash VARCHAR(200),
    locked_at TIMESTAMP(6),
    released_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT FK_deposits_mission FOREIGN KEY (mission_id) REFERENCES missions(id),
    CONSTRAINT FK_deposits_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    merchant VARCHAR(255),
    amount BIGINT NOT NULL,
    category VARCHAR(50),
    transacted_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT FK_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS my_data_caches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    category_expenses VARCHAR(2000) NOT NULL DEFAULT '{}',
    weekly_avg_expenses VARCHAR(2000) NOT NULL DEFAULT '{}',
    daily_available_amount BIGINT NOT NULL DEFAULT 0,
    last_updated_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT FK_my_data_caches_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS spending_embeddings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category VARCHAR(50) NOT NULL,
    merchant_name VARCHAR(255),
    amount BIGINT NOT NULL,
    embedding VARCHAR(10000),
    content VARCHAR(5000) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS mission_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(50) NOT NULL,
    mission_type VARCHAR(20) NOT NULL,
    limit_amount BIGINT,
    success_rate DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    embedding VARCHAR(10000),
    content VARCHAR(5000) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);
